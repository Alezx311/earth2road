def _write_cache(features: List[Dict[str, Any]], meta: Dict[str, Any],
                 key_dir: Path) -> None:
    key_dir.mkdir(parents=True, exist_ok=True)
    feats_path = key_dir / "features.geojson"
    data = json.dumps({"type": "FeatureCollection", "features": features}, ensure_ascii=False)
    payload = data.encode("utf-8")
    feats_path.write_bytes(payload)
    meta = dict(meta)
    meta["sha256_features"] = hashlib.sha256(payload).hexdigest()
    meta["cached_bytes"] = len(payload)
    meta["features"] = len(features)
    (key_dir / "meta.json").write_text(json.dumps(meta, ensure_ascii=False, indent=1), encoding="utf-8")


METRIC_KEYS = ("downloaded_bytes", "extracted_bytes", "index_bytes", "shard_bytes")


def _with_metrics(meta: Dict[str, Any]) -> Dict[str, Any]:
    """Ensure every audit/cache dict carries the metric keys (None = unknown,
    0 = none/not applicable), so CLI consumers can rely on their presence."""
    meta = dict(meta)
    for k in METRIC_KEYS:
        meta.setdefault(k, None)
    return meta


def _options_digest(source_cfg: Dict[str, Any], *, engine: str) -> str:
    """SHA-256 of the config options that change what gets extracted, plus the
    engine, so a cache written under different options/engine is never reused."""
    opts = {k: source_cfg.get(k) for k in (
        "release", "geo_q", "height_provenance", "height_unknown",
        "location_filter", "parquet_s3_template", "local_geojson")}
    opts["engine"] = engine
    raw = json.dumps(opts, sort_keys=True, ensure_ascii=False, default=str)
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def _read_cache_features(key_dir: Path) -> List[Dict[str, Any]]:
    doc = json.loads((key_dir / "features.geojson").read_text(encoding="utf-8"))
    return list(doc.get("features", []))


def _covers(cached_bbox: Sequence[float], bbox: Sequence[float]) -> bool:
    cw, cs, ce, cn = cached_bbox
    w, s, e, n = bbox
    return cw <= w and cs <= s and ce >= e and cn >= n


def _expand(bbox: Sequence[float], q: float) -> Tuple[float, float, float, float]:
    w, s, e, n = bbox
    return (math.floor(w / q) * q, math.floor(s / q) * q,
            math.ceil(e / q) * q, math.ceil(n / q) * q)


def _geo_key(bbox: Sequence[float], q: float) -> str:
    w, s, e, n = _expand(bbox, q)
    return f"{w:.4f}_{s:.4f}_{e:.4f}_{n:.4f}"


def _source_base(cache_dir: Path, source: str, release: str, bbox: Sequence[float],
                 geo_q: float) -> Tuple[Path, Dict[str, Any]]:
    key_dir = cache_dir / source / release / _geo_key(bbox, geo_q)
    meta = {
        "source": source,
        "release": release,
        "bbox_cached": list(_expand(bbox, geo_q)),
        "bbox_requested": list(bbox),
        "geo_q": geo_q,
    }
    return key_dir, meta


def _try_reuse(key_dir: Path, meta_default: Dict[str, Any], bbox: Sequence[float],
               offline: bool, options_digest: Optional[str] = None) -> Optional[Tuple[List[Dict[str, Any]], Dict[str, Any]]]:
    meta_path, feats_path = key_dir / "meta.json", key_dir / "features.geojson"
    if meta_path.exists() and feats_path.exists():
        try:
            meta = json.loads(meta_path.read_text(encoding="utf-8"))
        except Exception:
            meta = None
        same_opts = meta is not None and (options_digest is None
                                          or meta.get("options_digest") == options_digest)
        if (meta and meta.get("status") == "ok" and same_opts
                and _covers(meta.get("bbox_cached", []), bbox)):
            raw = feats_path.read_bytes()
            if hashlib.sha256(raw).hexdigest() == meta.get("sha256_features"):
                features = _read_cache_features(key_dir)
                add = {"status": "ok", "cached": True, "features": len(features),
                       "warnings": list(meta.get("warnings", [])), "error": None}
                return features, _with_metrics({**meta_default, **meta, **add})
    if offline:
        return [], _with_metrics({"status": "offline_cache_miss", "cached": False,
                                  "error": f"no valid cache at {key_dir} and offline mode refuses network",
                                  "warnings": []})
    return None


