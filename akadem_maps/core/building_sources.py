def dedup_osm_priority(features: Sequence[Dict[str, Any]],
                       osm_footprints: Sequence[Any]) -> Tuple[List[Dict[str, Any]], List[str]]:
    """OSM stays authoritative: drop every candidate feature whose polygon
    intersects any OSM footprint. Returns ``(kept, dropped_source_ids)``."""
    prepped = [prep(fp) for fp in osm_footprints
               if fp is not None and not fp.is_empty and fp.is_valid
               and fp.geom_type in ("Polygon", "MultiPolygon")]
    kept: List[Dict[str, Any]] = []
    dropped: List[str] = []
    for f in features:
        if any(p.intersects(shape(f["geometry"])) for p in prepped):
            dropped.append(f["properties"]["source_id"])
        else:
            kept.append(f)
    return kept, dropped


def dedup_duplicates(features: Sequence[Dict[str, Any]]) -> Tuple[List[Dict[str, Any]], List[str]]:
    """Deterministic dedup across ingested sources: the same ``source_id``
    anywhere collapses to the higher-priority source, and exactly matching
    footprints (coordinates equal to 1e-6) collapse the same way. Returns
    ``(kept, dropped_source_ids)``."""
    import shapely.wkt
    order = {src: i for i, src in enumerate(SOURCE_PRIORITY)}
    first_id: Dict[str, Dict[str, Any]] = {}
    geo_owner: Dict[str, str] = {}
    kept: List[Dict[str, Any]] = []
    dropped: List[str] = []
    for f in sorted(features, key=lambda f: (order.get(f["properties"]["source"], 9), f["properties"]["source_id"])):
        p = f["properties"]
        geom = shape(f["geometry"])
        gkey = shapely.wkt.dumps(geom, rounding_precision=6)
        if p["source_id"] in first_id or gkey in geo_owner:
            dropped.append(p["source_id"])
            continue
        first_id[p["source_id"]] = f
        geo_owner[gkey] = p["source_id"]
        kept.append(f)
    return kept, dropped


