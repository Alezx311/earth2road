def clean_height(value: Any) -> Optional[float]:
    """Finite, strictly positive height in metres, else None."""
    if value is None:
        return None
    try:
        v = float(value)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(v) or v <= 0:
        return None
    return v


def quadkey_bounds(qk: str) -> Tuple[float, float, float, float]:
    """WGS84 bounds ``(west, north, east, south)`` of a Bing quadkey cell."""
    qk = str(qk)
    if not qk or not qk.isdigit():
        raise ValueError(f"not a quadkey: {qk!r}")
    z = len(qk)
    n = 1 << z
    x = y = 0
    for i, ch in enumerate(qk):
        d = int(ch)
        bit = 1 << (z - 1 - i)
        if d & 1:
            x |= bit
        if d & 2:
            y |= bit
    west = x / n * 360.0 - 180.0
    east = (x + 1) / n * 360.0 - 180.0
    north = math.degrees(math.atan(math.sinh(math.pi * (1 - 2 * y / n))))
    south = math.degrees(math.atan(math.sinh(math.pi * (1 - 2 * (y + 1) / n))))
    return (west, north, east, south)


def quadkey_for(lon: float, lat: float, z: int) -> str:
    """Bing quadkey of the tile containing ``(lon, lat)`` at zoom ``z``."""
    n = 1 << z
    x = min(max(int((lon + 180.0) / 360.0 * n), 0), n - 1)
    y = min(max(int((1 - math.asinh(math.tan(math.radians(lat))) / math.pi) / 2 * n), 0), n - 1)
    out = []
    for i in range(z - 1, -1, -1):
        d = (((y >> i) & 1) << 1) | ((x >> i) & 1)
        out.append(str(d))
    return "".join(out)


def check_bbox(bbox: Sequence[float]) -> Tuple[float, float, float, float]:
    """Validate a ``[west, south, east, north]`` lon/lat bbox."""
    if bbox is None or len(bbox) != 4:
        raise ValueError(f"bbox must be [west, south, east, north], got {bbox!r}")
    w, s, e, n = (float(v) for v in bbox)
    if not all(math.isfinite(v) for v in (w, s, e, n)):
        raise ValueError(f"bbox contains non-finite values: {bbox!r}")
    if not (w < e and s < n):
        raise ValueError(f"bbox must satisfy west<east and south<north: {bbox!r}")
    if not (-180 <= w <= 180 and -180 <= e <= 180 and -90 <= s <= 90 and -90 <= n <= 90):
        raise ValueError(f"bbox outside WGS84: {bbox!r}")
    return (w, s, e, n)


def check_url(url: str, allowed_hosts: Sequence[str], path_prefix: Optional[str] = None,
              suffix: Optional[str] = None) -> str:
    """URL safety gate: https only, host allow-listed, no credentials, no '..',
    optional path-prefix and filename-suffix constraints."""
    p = __import__("urllib.parse", fromlist=["urlparse"]).urlparse(url)
    if p.scheme != "https":
        raise ValueError(f"refusing non-https URL: {url!r}")
    if p.hostname not in allowed_hosts:
        raise ValueError(f"refusing URL on unexpected host {p.hostname!r}")
    if p.username or p.password:
        raise ValueError(f"refusing URL with credentials: {url!r}")
    if ".." in p.path.split("/"):
        raise ValueError(f"refusing URL with dot-dot path: {url!r}")
    if path_prefix and not p.path.startswith(path_prefix):
        raise ValueError(f"URL path {p.path!r} outside allowed prefix {path_prefix!r}")
    if suffix and not p.path.endswith(suffix):
        raise ValueError(f"URL path {p.path!r} does not end with {suffix!r}")
    return url


def fetch_url(url: str, max_bytes: int, max_time: float, chunk: int = 1 << 16) -> bytes:
    """Streamed GET bounded by compressed-byte and wall-clock caps."""
    t0 = time.monotonic()
    try:
        with requests.get(url, stream=True, timeout=(30, max_time)) as resp:
            resp.raise_for_status()
            out = io.BytesIO()
            total = 0
            for part in resp.iter_content(chunk_size=chunk):
                total += len(part)
                if total > max_bytes:
                    raise FetchError(f"download exceeded {max_bytes} bytes cap at {url}")
                if time.monotonic() - t0 > max_time:
                    raise FetchError(f"download exceeded {max_time}s cap at {url}")
                out.write(part)
            return out.getvalue()
    except requests.RequestException as exc:
        raise FetchError(f"GET {url} failed: {exc}") from exc


FetchFn = Callable[[str, int, float], bytes]


