def _load_local_bytes(path: Path, max_bytes: int) -> bytes:
    total = 0
    out = io.BytesIO()
    with open(path, "rb") as f:
        while True:
            chunk = f.read(1 << 20)
            if not chunk:
                break
            total += len(chunk)
            if total > max_bytes:
                raise SourceError(f"local file {path} exceeds {max_bytes} bytes cap")
            out.write(chunk)
    return out.getvalue()


def iterate_geojson_bytes(data: bytes):
    """Yield features from a FeatureCollection JSON, a single Feature object,
    or line-delimited GeoJSON (optionally gzipped bytes)."""
    if data[:2] == b"\x1f\x8b":
        data = gzip.decompress(data)
    text = data.decode("utf-8-sig", "replace").lstrip()
    if text.startswith("{"):
        try:
            doc = json.loads(text)
        except json.JSONDecodeError:
            doc = None
        if doc is not None:
            if isinstance(doc, dict) and doc.get("type") == "Feature":
                yield doc
                return
            feats = doc.get("features", []) if isinstance(doc, dict) else []
            for f in feats:
                yield f
            return
    for line in text.splitlines():
        line = line.strip()
        if not line or line[0] == "[":
            continue
        try:
            yield json.loads(line)
        except json.JSONDecodeError:
            continue


def ingest_overture_local(bbox: Sequence[float], source_cfg: Dict[str, Any], cache_dir: Path,
                          local_path: Path, *, offline: bool = False) -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    """Ingest a genuine local Overture extract (GeoJSON/GeoJSONSeq, optional
    .gz). Re-caches when the local input changes (SHA-256 tracked)."""
    bbox = check_bbox(bbox)
    t0 = time.monotonic()
    release = source_cfg["release"]
    geo_q = float(source_cfg.get("geo_q", 0.002))
    if not local_path.is_file():
        raise SourceError(f"local Overture input not found: {local_path}")
    input_sha = hashlib.sha256(_load_local_bytes(local_path, int(source_cfg.get("local_max_bytes", 2 << 30)))).hexdigest()
    digest = _options_digest(source_cfg, engine="local")
    key_dir, meta = _source_base(cache_dir, "overture", release, bbox, geo_q)
    meta_path = key_dir / "meta.json"
    if meta_path.exists():
        try:
            old = json.loads(meta_path.read_text(encoding="utf-8"))
        except Exception:
            old = {}
        if (old.get("status") == "ok" and _covers(old.get("bbox_cached", []), bbox)
                and old.get("input_sha256") == input_sha
                and old.get("options_digest") == digest):
            raw = (key_dir / "features.geojson").read_bytes()
            if hashlib.sha256(raw).hexdigest() == old.get("sha256_features"):
                add = {"status": "ok", "cached": True, "features": len(_read_cache_features(key_dir)),
                       "warnings": [], "error": None}
                return _read_cache_features(key_dir), _with_metrics({**meta, **old, **add})
    if offline:
        return [], _with_metrics({"status": "offline_cache_miss", "features": 0,
                                  "duration_s": time.monotonic() - t0, "warnings": [],
                                  "error": f"no valid cache at {key_dir} and offline forbids reading {local_path}"})
    data = _load_local_bytes(local_path, int(source_cfg.get("local_max_bytes", 2 << 30)))
    features: List[Dict[str, Any]] = []
    seen: set = set()
    warnings: List[str] = []
    for raw in iterate_geojson_bytes(data):
        feat = normalize_feature(raw, source="overture", release=release,
                                 license_=source_cfg["license"],
                                 height_provenance=source_cfg.get("height_provenance"))
        if feat is None:
            continue
        if not intersects_bbox(shape(feat["geometry"]), bbox):
            continue
        sid = feat["properties"]["source_id"]
        if sid in seen:
            continue
        seen.add(sid)
        features.append(feat)
    if not features:
        warnings.append(f"overture {release}: no matching features in {local_path.name}")
    features = _finish(features)
    meta.update(_with_metrics({
        "status": "ok", "license": source_cfg["license"],
        "options_digest": digest, "engine": "local",
        "input_sha256": input_sha, "input_path": str(local_path),
        "downloaded_bytes": 0, "extracted_bytes": len(data),
        "duration_s": time.monotonic() - t0, "warnings": warnings, "error": None,
    }))
    _write_cache(features, meta, key_dir)
    return features, _with_metrics({**meta, "cached": False})


def _duckdb_sql(source_cfg: Dict[str, Any], bbox: Sequence[float], out_path: Path) -> str:
    release = source_cfg["release"]
    if not _RELEASE_RE.match(release):
        raise SourceError(f"refusing non-release release string {release!r}")
    url = (source_cfg.get("parquet_s3_template") or "").format(release=release)
    if not url.startswith("s3://overturemaps-us-west-2/release/") or "{release}" in url:
        raise SourceError(f"parquet URL template not pinned/trusted: {url!r}")
    w, s, e, n = bbox
    out = str(out_path).replace("'", "")
    if not out or "'" in str(out_path):
        raise SourceError("invalid temporary output path for duckdb")
    return (
        "INSTALL httpfs; LOAD httpfs; INSTALL spatial; LOAD spatial;\n"
        "SET s3_region='us-west-2';\n"
        "SET threads=2;\n"
        "PRAGMA memory_limit='2GB';\n"
        "COPY (\n"
        "  SELECT id, height, geometry\n"
        "  FROM read_parquet('" + url + "', hive_partitioning=1)\n"
        "  WHERE bbox.xmin < " + repr(e) + " AND bbox.xmax > " + repr(w) +
        "    AND bbox.ymin < " + repr(n) + " AND bbox.ymax > " + repr(s) + "\n"
        ") TO '" + out + "' (FORMAT GDAL, DRIVER 'GeoJSONSeq');\n"
    )


def ingest_overture_duckdb(bbox: Sequence[float], source_cfg: Dict[str, Any], cache_dir: Path,
                           *, offline: bool = False, duckdb_cli: Optional[str] = None,
                           timeout_s: Optional[float] = None) -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    """Optional bounded Overture query via the duckdb CLI as an isolated
    subprocess (argument list, no shell). Transfers only the parquet row groups
    whose bbox stats intersect the request. Requires a duckdb binary; set
    ``building_enrichment.sources.overture.duckdb: true`` and provide the binary
    via the config (``duckdb_cli``), env ``DUCKDB_CLI`` or PATH."""
    bbox = check_bbox(bbox)
    t0 = time.monotonic()
    release = source_cfg["release"]
    cli = duckdb_cli or os.environ.get("DUCKDB_CLI") or source_cfg.get("duckdb_cli") \
        or shutil.which("duckdb")
    if not cli:
        for cand in (ROOT / ".cache" / "building-deps" / "duckdb-cli",
                     ROOT / ".cache" / "building-deps" / "duckdb" / "duckdb"):
            if cand.is_file():
                cli = str(cand)
                break
    if not cli:
        raise SourceError(
            "overture duckdb requested but no duckdb CLI found (set DUCKDB_CLI or "
            "pass a genuine local Overture GeoJSON via 'local_geojson' instead)")
    geo_q = float(source_cfg.get("geo_q", 0.002))
    digest = _options_digest(source_cfg, engine="duckdb")
    key_dir, meta = _source_base(cache_dir, "overture", release, bbox, geo_q)
    reused = _try_reuse(key_dir, meta, bbox, offline, options_digest=digest)
    if reused:
        return reused
    if offline:
        return [], _with_metrics({"status": "offline_cache_miss", "features": 0,
                                  "duration_s": time.monotonic() - t0, "warnings": [],
                                  "error": f"no valid cache for {release} at {key_dir}"})
    tmp = cache_dir / "overture" / release / "tmp"
    tmp.mkdir(parents=True, exist_ok=True)
    out_path = tmp / f"bbox_{_geo_key(bbox, geo_q)}.geojsonseq"
    sql = _duckdb_sql(source_cfg, bbox, out_path)
    try:
        proc = subprocess.run([cli, "-c", sql], capture_output=True, text=True,
                              timeout=timeout_s or float(source_cfg.get("duckdb_timeout", 600)))
    except FileNotFoundError as exc:
        raise SourceError(f"duckdb CLI not runnable: {cli}") from exc
    except subprocess.TimeoutExpired as exc:
        raise SourceError(f"duckdb query timed out after {timeout_s or 600}s") from exc
    if proc.returncode != 0 or not out_path.exists():
        tail = (proc.stderr or proc.stdout or "")[-1000:]
        raise SourceError(f"duckdb query failed (rc={proc.returncode}): {tail}")
    data = out_path.read_bytes()
    features = []
    for raw in iterate_geojson_bytes(data):
        feat = normalize_feature(raw, source="overture", release=release,
                                 license_=source_cfg["license"],
                                 height_provenance=source_cfg.get("height_provenance"))
        if feat is None:
            continue
        if not intersects_bbox(shape(feat["geometry"]), bbox):
            continue
        features.append(feat)
    out_path.unlink(missing_ok=True)
    features = _finish(features)
    # Network bytes the duckdb CLI transferred are NOT measured by this process
    # (duckdb does its own HTTP) and must never be inferred from output size;
    # report only what we know: the extracted GeoJSON output bytes.
    meta.update(_with_metrics({
        "status": "ok", "license": source_cfg["license"],
        "options_digest": digest, "engine": "duckdb",
        "downloaded_bytes": None, "extracted_bytes": len(data),
        "duration_s": time.monotonic() - t0, "warnings": [], "error": None,
    }))
    _write_cache(features, meta, key_dir)
    return features, _with_metrics({**meta, "cached": False})


