def _geom_finite(geom: Any) -> bool:
    rings: list = []
    if geom.geom_type == "Polygon":
        rings = [geom.exterior, *geom.interiors]
    elif geom.geom_type == "MultiPolygon":
        for part in geom.geoms:
            rings += [part.exterior, *part.interiors]
    else:
        return False
    for ring in rings:
        for c in ring.coords:
            if not all(math.isfinite(v) for v in c):
                return False
    return True


def _as_lists(obj: Any) -> Any:
    """JSON-stable structure: tuples -> lists (recursing into dicts) so a
    fresh normal form equals the same form after a cache round-trip."""
    if isinstance(obj, dict):
        return {k: _as_lists(v) for k, v in obj.items()}
    if isinstance(obj, (tuple, list)):
        return [_as_lists(x) for x in obj]
    return obj


def normalize_feature(raw: Dict[str, Any], *, source: str, release: str, license_: str,
                      height_provenance: Optional[str], height_field: Optional[str] = "height",
                      id_field: str = "id") -> Optional[Dict[str, Any]]:
    """Convert one raw source feature into the normal form, or None if it is
    invalid (non-polygon, empty, invalid topology, non-finite coordinates)."""
    geom_raw = raw.get("geometry")
    if geom_raw is None:
        return None
    try:
        geom = shape(geom_raw)
    except Exception:
        return None
    if geom.is_empty or not geom.is_valid or geom.geom_type not in ("Polygon", "MultiPolygon"):
        return None
    if not _geom_finite(geom):
        return None
    props = raw.get("properties") or {}
    source_id = str(props.get(id_field) or "").strip()
    if not source_id:  # deterministic fallback id from the geometry itself
        x, y = float(geom.centroid.x), float(geom.centroid.y)
        source_id = f"{source}-auto-{x:.6f}-{y:.6f}-{geom.area:.3f}"
    height = clean_height(props.get(height_field)) if height_field else None
    return {
        "type": "Feature",
        "geometry": _as_lists(mapping(geom)),
        "properties": {
            "source": source,
            "source_id": source_id,
            "release": release,
            "license": license_,
            "height": height,
            "height_provenance": height_provenance if height is not None else None,
        },
    }


def intersects_bbox(geom: Any, bbox: Sequence[float]) -> bool:
    """Proper intersection (keeps crossing/touching/containing features; drops
    only disjoint ones — deliberately NOT a containment-only test)."""
    w, s, e, n = check_bbox(bbox)
    return geom.intersects(box(w, s, e, n))


def _finish(features: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    seen: set = set()
    out: List[Dict[str, Any]] = []
    for f in features:
        sid = f["properties"]["source_id"]
        if sid in seen:
            continue
        seen.add(sid)
        out.append(f)
    order = {s: i for i, s in enumerate(SOURCE_PRIORITY)}
    out.sort(key=lambda f: (order.get(f["properties"]["source"], len(order)),
                            f["properties"]["source_id"]))
    return out


