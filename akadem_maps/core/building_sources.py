def _resolve(path: Optional[str], default: Path, base: Optional[Path] = None) -> Path:
    if not path:
        return default
    p = Path(path).expanduser()
    return p if p.is_absolute() else (base or ROOT) / p


def load_candidates(cfg: Dict[str, Any], *, offline: bool = False,
                    cache_dir: Optional[Path] = None,
                    sources_config: Optional[Any] = None,
                    fetch: FetchFn = fetch_url,
                    duckdb_cli: Optional[str] = None,
                    base: Optional[Path] = None) -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    """Return ``(features, audit)`` for one map config dict.

    Relative paths resolve against ``base`` (the build's config root); only legacy
    callers without it fall back to the repository checkout.

    ``cfg`` is a map config (as in ``config/<id>.json``) with a bbox
    ``[west, south, east, north]``; enrichment runs only when
    ``cfg["building_enrichment"]["enabled"]`` is true (explicit opt-in, default
    off). ``building_enrichment`` keys:

        enabled          bool (required for any ingestion)
        sources_config   path or dict (default config/building_sources.json)
        cache_dir        path (default .cache/buildings)
        sources          dict of {name: override} or list of names to limit
        sources.overture.local_geojson   genuine local Overture GeoJSON input
        sources.overture.duckdb          true to attempt the duckdb CLI query

    The returned audit dict (JSON-serialisable) is:

        status     ok | partial | error | disabled | offline_cache_miss | no_source_data
        map_id, bbox_requested, features,
        sources {name: {status, release, license, features, cached,
                        downloaded_bytes, duration_s, warnings, error}}

    On any source error no cache entry is written for that source; statuses lets
    integration refuse to proceed when data is missing rather than empty.
    """
    raw_bbox = cfg.get("bbox")
    if raw_bbox is None:
        raise ValueError("cfg['bbox'] [west,south,east,north] is required for enrichment")
    audit: Dict[str, Any] = {
        "map_id": str(cfg.get("id", "?")),
        "bbox_requested": list(raw_bbox),
        "features": 0,
        "sources": {},
        "warnings": [],
    }
    bbox = check_bbox(list(raw_bbox))
    en = cfg.get("building_enrichment")
    if not isinstance(en, dict) or not en.get("enabled"):
        audit["status"] = "disabled"
        return [], audit

    sc = sources_config or en.get("sources_config") or DEFAULT_SOURCES_CONFIG
    if isinstance(sc, (str, Path)):
        source_config = json.loads(_resolve(str(sc), DEFAULT_SOURCES_CONFIG, base).read_text(encoding="utf-8"))
    elif isinstance(sc, dict):
        source_config = sc
    else:
        raise ValueError(f"bad sources_config: {sc!r}")

    cache_root = cache_dir if cache_dir is not None else _resolve(en.get("cache_dir"), DEFAULT_CACHE_DIR, base)

    active = en.get("sources")
    if isinstance(active, (list, tuple, set)):
        active = {name: {} for name in active}
    active = active or {}

    features: List[Dict[str, Any]] = []
    statuses = set()
    for name in SOURCE_PRIORITY:
        if active and name not in active:
            continue
        base_cfg = source_config.get("sources", {}).get(name) or {}
        override = active.get(name) or {}
        src_cfg = {**base_cfg, **{k: v for k, v in override.items() if v is not None}}
        try:
            src_audit: Dict[str, Any]
            if name == "microsoft":
                feats, src_audit = ingest_microsoft(bbox, src_cfg, cache_root,
                                                    offline=offline, fetch=fetch)
            else:  # overture
                local = src_cfg.get("local_geojson")
                if local:
                    feats, src_audit = ingest_overture_local(
                        bbox, src_cfg, cache_root, _resolve(str(local), (base or ROOT) / "none.geojson", base),
                        offline=offline)
                elif src_cfg.get("duckdb"):
                    feats, src_audit = ingest_overture_duckdb(bbox, src_cfg, cache_root,
                                                              offline=offline, duckdb_cli=duckdb_cli)
                else:
                    feats, src_audit = [], _with_metrics({
                        "status": "no_input", "release": src_cfg.get("release"),
                        "license": src_cfg.get("license"), "features": 0,
                        "downloaded_bytes": 0, "extracted_bytes": 0, "duration_s": 0.0,
                        "warnings": ["no local_geojson and duckdb not enabled; "
                                     "nothing genuine to ingest"], "error": None,
                    })
            features.extend(feats)
            statuses.add(src_audit.get("status", "error"))
            audit["sources"][name] = src_audit
        except SourceError as exc:
            statuses.add("error")
            audit["sources"][name] = _with_metrics({
                "status": "error", "release": src_cfg.get("release"),
                "license": src_cfg.get("license"), "features": 0, "downloaded_bytes": 0,
                "extracted_bytes": 0, "duration_s": 0.0, "warnings": [], "error": str(exc),
            })

    features = _finish(features)
    audit["features"] = len(features)
    if "error" in statuses:
        overall = "error" if statuses == {"error"} else "partial"
    elif "offline_cache_miss" in statuses:
        overall = "offline_cache_miss"
    elif not statuses or statuses == {"no_input"}:
        overall = "no_source_data"
    else:
        overall = "ok"
    audit["status"] = overall
    audit["warnings"] = [f'{k}: {v.get("warnings", [])}' for k, v in audit["sources"].items() if v.get("warnings")]
    return features, audit