"""Map-independent building enrichment sources (DATA package).

Ingests two public building-footprint sources and normalises them into one
documented form so a later integration step can merge them with OSM.

Sources
-------
* Microsoft GlobalMLBuildingFootprints, release 2026-08-13, CDLA-Permissive-2.0.
  Worldwide per-quadkey GeoJSONL files (gzipped); every height is an ML estimate
  and the dataset marks unknown heights as -1. Index:
  https://bfppub.blob.core.windows.net/$web/2026-08-13/dataset-links.csv
* Overture Maps buildings, pinned release (config), ODbL-1.0. GeoParquet on S3;
  read by bbox via the optional duckdb CLI (isolated subprocess) or from a
  genuine local GeoJSON/GeoJSONSeq file supplied by the user. Overture height is
  treated as *assumed* (mix of OSM tags and modeled estimates), never claimed
  measured.

Normal form (the only shape this module emits)
---------------------------------------------
GeoJSON ``Feature`` with geometry ``Polygon`` or ``MultiPolygon`` in EPSG4326
(lon/lat, WGS84) and exactly these properties::

    source            "microsoft" | "overture"
    source_id         stable id as published (deterministic fallback otherwise)
    release           source release string, e.g. "2026-08-13"
    license           license id, e.g. "CDLA-Permissive-2.0", "ODbL-1.0"
    height            float in metres or None. Finite and positive only;
                      unknown/non-finite/<=0 heights become None.
    height_provenance "ml_estimated" | "overture_assumed", or None when
                      height is None

Features are filtered to proper intersection with the requested bbox (a feature
that crosses, touches, contains or is contained by the bbox is kept; only
disjoint features are dropped), invalid/empty/non-finite geometries and
non-polygon types are dropped, intra-source duplicate ``source_id`` values are
dropped deterministically, and the result is sorted by ``(source, source_id)``.

Caching
-------
Fetch results are cached per ``(source, release, geography)`` where geography is
the requested bbox expanded outward onto a configurable grid (default 0.002°,
~220 m). ``offline=True`` reuses the cache only; a miss is reported as
``offline_cache_miss`` and never silently filled. A failed fetch is never cached
as an empty success: on any download/parse error the affected source reports
status ``error`` and no cache entry is written. Cache entries carry a SHA-256 of
the stored features so reuse is verified.

Public API
----------
    load_candidates(cfg, offline=False, ...) -> (features, audit)
    dedup_osm_priority(features, osm_footprints) -> (kept, dropped_ids)
    dedup_duplicates(features) -> (kept, dropped)
    quadkey_bounds(qk), quadkey_for(lon, lat, z)      # Bing quadkey helpers
    ingest_microsoft / ingest_overture_local / ingest_overture_duckdb

`load_candidates` stays OFF for every map until the map config sets
``building_enrichment.enabled: true`` (integration deliberately explicit).

Anti-magic notes
----------------
* No secret handling anywhere (no credentials are needed; URLs are config-pinned
  and cross-checked against allow-listed hosts/path prefixes).
* duckdb runs as an isolated subprocess with an argument list (never a shell);
  the SQL embeds only software-generated values: a regex-validated release
  string, float-formatted bbox numbers, a config-pinned URL template and a
  cache directory path generated by this module.
* The duckdb query is *bounded, not literally worldless*: it applies row-group
  predicate push-down on the ``bbox`` columns of Overture's partitioned files,
  so the transferred *data rows* are limited to intersecting row groups, but
  duckdb still reads parquet metadata (file/row-group/column stats) of many
  world files and both worlds' network share is internal to duckdb and
  **NOT measured** by this module. Audited byte counts are therefore honest:
  ``downloaded_bytes`` is network bytes this process fetched itself (microsoft
  index+shards, ``None`` when unmeasurable, e.g. the duckdb engine),
  ``extracted_bytes`` is the size of the GeoJSON output actually produced
  (for duckdb: the engine's GeoJSONSeq output), and ``index_bytes``/``shard_bytes``
  split the microsoft download. Timeouts/caps are set via config
  (``duckdb_timeout``, ``file_caps``/``index_caps``, ``SET threads=2``,
  ``PRAGMA memory_limit='2GB'``); they bound the query, they do not bound the
  metadata volume duckdb reads.
"""
