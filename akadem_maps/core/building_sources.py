def _parse_index(text: str) -> List[Dict[str, str]]:
    rows = []
    for r in csv.DictReader(io.StringIO(text)):
        rows.append({k.strip().lower(): (v or "").strip() for k, v in r.items()})
    return rows


def select_quadkey_rows(rows: Sequence[Dict[str, str]], bbox: Sequence[float],
                        location: Optional[str] = None) -> List[Dict[str, str]]:
    """Index rows whose quadkey cell intersects the bbox (proper cell overlap,
    not containment). Optional Location filter is a cheap pre-filter."""
    w, s, e, n = check_bbox(bbox)
    out = []
    for r in rows:
        if location and r.get("location") != location:
            continue
        if not r.get("quadkey") or not r.get("url"):
            continue
        try:
            cw, cn, ce, cs = quadkey_bounds(r["quadkey"])
        except ValueError:
            continue
        if cw < e and ce > w and cs < n and cn > s:
            out.append(r)
    out.sort(key=lambda r: r["quadkey"])
    return out


def _iter_geojsonl_gz(data: bytes, t0: float, max_time: float):
    with gzip.GzipFile(fileobj=io.BytesIO(data)) as f:
        for line in f:
            if time.monotonic() - t0 > max_time:
                raise FetchError("decompression exceeded time cap")
            line = line.decode("utf-8", "replace").strip()
            if not line or line[0] == "[":
                continue  # tolerate a wrapped FeatureCollection line
            try:
                yield json.loads(line)
            except json.JSONDecodeError:
                continue


def fetch_index(source_cfg: Dict[str, Any], cache_root: Path, *, offline: bool,
                fetch: FetchFn = fetch_url) -> bytes:
    """Index CSV for the release, cached next to the per-geography caches so a
    later offline run can resolve quadkey URLs without the network."""
    release = source_cfg["release"]
    idx_dir = cache_root / "microsoft" / release
    idx_file = idx_dir / "index.csv"
    idx_meta = idx_dir / "index.meta.json"
    pinned = source_cfg.get("index_sha256")
    if idx_file.exists() and idx_meta.exists():
        meta = json.loads(idx_meta.read_text(encoding="utf-8"))
        data = idx_file.read_bytes()
        if (meta.get("sha256") == pinned or (not pinned and hashlib.sha256(data).hexdigest() == meta.get("sha256"))):
            return data
    if offline:
        raise SourceError(f"index for release {release} not cached and offline forbids fetching")
    try:
        url = check_url(source_cfg["index_url"], source_cfg["url_hosts"])
    except ValueError as exc:
        raise SourceError(str(exc)) from exc
    caps = source_cfg.get("index_caps", {})
    data = fetch(url, int(caps.get("max_bytes", 64 * 1024 * 1024)), float(caps.get("max_time", 120)))
    if pinned and hashlib.sha256(data).hexdigest() != pinned:
        raise SourceError(f"index SHA-256 mismatch for {release} (pinned {pinned})")
    idx_dir.mkdir(parents=True, exist_ok=True)
    idx_file.write_bytes(data)
    idx_meta.write_text(json.dumps({"sha256": hashlib.sha256(data).hexdigest(),
                                    "bytes": len(data), "url": url},
                                   ensure_ascii=False, indent=1), encoding="utf-8")
    return data


def ingest_microsoft(bbox: Sequence[float], source_cfg: Dict[str, Any], cache_dir: Path,
                     *, offline: bool = False, fetch: FetchFn = fetch_url,
                     t0: Optional[float] = None) -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    """Fetch/normalise Microsoft footprints for a bbox; cache per release+geo."""
    bbox = check_bbox(bbox)
    t0 = t0 if t0 is not None else time.monotonic()
    release = source_cfg["release"]
    geo_q = float(source_cfg.get("geo_q", 0.002))
    digest = _options_digest(source_cfg, engine="microsoft")
    key_dir, meta = _source_base(cache_dir, "microsoft", release, bbox, geo_q)
    reused = _try_reuse(key_dir, meta, bbox, offline, options_digest=digest)
    if reused:
        return reused
    if offline:
        return [], _with_metrics({"status": "offline_cache_miss", "features": 0,
                                  "duration_s": time.monotonic() - t0, "warnings": [],
                                  "error": f"no valid cache for {release} at {key_dir}"})

    index_text = fetch_index(source_cfg, cache_dir, offline=False, fetch=fetch)
    index_bytes = len(index_text)
    rows = select_quadkey_rows(_parse_index(index_text.decode("utf-8-sig")), bbox,
                               location=source_cfg.get("location_filter"))
    if not rows:
        raise SourceError(
            f"microsoft {release}: no index quadkeys intersect bbox {bbox}; "
            "refusing to cache an empty result (cache requires verified coverage)")

    caps = source_cfg.get("file_caps", {})
    max_bytes = int(caps.get("max_bytes", 250 * 1024 * 1024))
    max_time = float(caps.get("max_time", 300))
    host_ok = source_cfg["url_hosts"]
    prefix = source_cfg.get("data_path_prefix")
    features: List[Dict[str, Any]] = []
    seen: set = set()
    shard_bytes = 0
    warnings: List[str] = []
    for r in rows:
        try:
            url = check_url(r["url"], host_ok, path_prefix=prefix, suffix=".csv.gz")
        except ValueError as exc:
            raise SourceError(str(exc)) from exc
        data = fetch(url, max_bytes, max_time)
        shard_bytes += len(data)
        for raw in _iter_geojsonl_gz(data, t0, max_time):
            feat = normalize_feature(raw, source="microsoft", release=release,
                                     license_=source_cfg["license"],
                                     height_provenance=source_cfg.get("height_provenance"))
            if feat is None:
                continue
            if not intersects_bbox(shape(feat["geometry"]), bbox):
                continue
            sid = feat["properties"]["source_id"]
            if sid in seen:
                continue
            seen.add(sid)
            features.append(feat)
    if not features:
        warnings.append(f"microsoft {release}: no matching features in {len(rows)} quadkey file(s)")
    features = _finish(features)
    meta.update(_with_metrics({
        "status": "ok", "license": source_cfg["license"],
        "options_digest": digest, "engine": "microsoft",
        "index_bytes": index_bytes, "shard_bytes": shard_bytes,
        "downloaded_bytes": index_bytes + shard_bytes, "extracted_bytes": 0,
        "duration_s": time.monotonic() - t0,
        "quadkey_files": len(rows), "warnings": warnings, "error": None,
    }))
    _write_cache(features, meta, key_dir)
    return features, _with_metrics({**meta, "cached": False})


